// Explicit opt-in: execute production sync SQL against transaction-local TEMP tables only.
import test from 'node:test'
import assert from 'node:assert/strict'
import {mkdtempSync} from 'node:fs'
import {tmpdir} from 'node:os'
import {join} from 'node:path'
import {randomUUID} from 'node:crypto'
import {spawnSync} from 'node:child_process'

test('PostgreSQL source deltas, repeat sync and real-site comments are preserved',{skip:process.env.PHONE_TEST_POSTGRES!=='1'},async()=>{
 process.env.PHONE_DEMO='1';process.env.PHONE_DEMO_DB=join(mkdtempSync(join(tmpdir(),'phone-pg-refresh-')),'test.sqlite')
 const r=await import('../src/lib/demo/runtime.mjs'),{syncPublic}=await import('./sync-public.mjs')
 const author=randomUUID(),post=randomUUID(),source=randomUUID(),localComment=randomUUID()
 r.execute("INSERT INTO boards(id,slug,name) VALUES(4,'qna','질문')")
 r.execute('INSERT INTO profiles(id,username,display_name,created_at) VALUES(?,?,?,?)',[author,'test','테스트','2026-10-20T00:00:00Z'])
 r.execute('INSERT INTO collected(id,source_id,url,title,content,authored_at,collected_at,fingerprint,source_view_count,source_upvotes,source_downvotes) VALUES(?,?,?,?,?,?,?,?,?,?,?)',[source,'ppomppu','https://www.ppomppu.co.kr/zboard/view.php?id=phone&no=9999999','테스트','본문','2026-10-20T00:00:00Z','2026-10-20T00:00:00Z',source,100,10,2])
 r.execute("INSERT INTO rewrites VALUES(?,?,'gemini-batch-reviewed',?,'published',NULL)",[source,'{}','2026-10-20T00:00:00Z'])
 r.execute("INSERT INTO posts(id,board_id,author_id,title,content,created_at,updated_at,generator,source_id,view_count,upvotes,downvotes) VALUES(?,4,?,'제목','본문',?,?,'ai-rewrite',?,100,10,2)",[post,author,'2026-10-20T00:00:00Z','2026-10-20T00:00:00Z',source])
 const commands=[],runSql=sql=>{commands.push(sql.replace(/^BEGIN;/,'').replace(/COMMIT;\s*$/,''));return {status:0}}
 syncPublic({runSql})
 r.execute('UPDATE collected SET source_view_count=150,source_upvotes=12,source_downvotes=1 WHERE id=?',[source])
 r.execute('UPDATE posts SET updated_at=? WHERE id=?',['2026-10-21T00:00:00Z',post])
 syncPublic({runSql})
 const sql=`BEGIN;
 CREATE TEMP TABLE profiles(id uuid PRIMARY KEY,username text,display_name text,password_hash text,bio text,created_at timestamptz,is_test boolean);
 CREATE TEMP TABLE boards(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,slug text UNIQUE,name text,type text,allow_anonymous boolean,description text,sort int);
 CREATE TEMP TABLE posts(id uuid PRIMARY KEY,board_id int,author_id uuid,is_anonymous boolean,title text,content text,status text,source text,source_ref text,created_at timestamptz,updated_at timestamptz,view_count int,upvotes int,downvotes int,comment_count int);
 CREATE TEMP TABLE comments(id uuid PRIMARY KEY,post_id uuid,parent_id uuid,author_id uuid,content text,created_at timestamptz,is_anonymous boolean,status text DEFAULT 'published');
 CREATE TEMP TABLE community_rewrite_provenance(post_id uuid PRIMARY KEY,source_url text,source_record_id uuid,model text,published_at timestamptz DEFAULT now(),source_metrics jsonb);
 CREATE TEMP TABLE community_pipeline_status(id int PRIMARY KEY,data jsonb);
 SET LOCAL search_path=pg_temp;
 INSERT INTO boards(slug,name) VALUES('qna','질문');
 ${commands[0]}
 UPDATE posts SET view_count=view_count+7,upvotes=upvotes+3,downvotes=downvotes+1 WHERE id='${post}';
 INSERT INTO comments(id,post_id,author_id,content) VALUES('${localComment}','${post}','${author}','local user');
 ${commands[1]}
 ${commands[1]}
 UPDATE posts SET content=content||'<p data-source-provenance="true"><a href="https://example.invalid/private-source">원문 출처</a></p>' WHERE id='${post}';
 ${commands[1]}
 DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM posts WHERE content LIKE '%data-source-provenance%' OR content LIKE '%private-source%') THEN RAISE EXCEPTION 'Source provenance leaked into public content'; END IF;
 IF NOT EXISTS(SELECT 1 FROM community_rewrite_provenance WHERE post_id='${post}' AND source_url IS NOT NULL) THEN RAISE EXCEPTION 'Private provenance lost'; END IF;
 IF NOT EXISTS(SELECT 1 FROM posts WHERE id='${post}' AND view_count=157 AND upvotes=15 AND downvotes=2 AND comment_count=1) THEN RAISE EXCEPTION 'Counter delta or repeat sync failed'; END IF;
 IF NOT EXISTS(SELECT 1 FROM comments WHERE id='${localComment}' AND content='local user') THEN RAISE EXCEPTION 'Local comment changed'; END IF;
 END $$;
 ROLLBACK;`
 const response=spawnSync('runuser',['-u','postgres','--','psql','-X','-v','ON_ERROR_STOP=1','-q','-d','phonecommunity'],{input:sql,encoding:'utf8'})
 assert.equal(response.status,0,response.stderr)
})
