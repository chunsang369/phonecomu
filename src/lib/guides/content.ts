export const getGuide = (slug: string) => GUIDES.find((g) => g.slug === slug)

/** 용어사전 DefinedTermSet 용 (glossary 문서의 표에서 추출) */
export function glossaryTerms() {
  const g = getGuide('glossary')
  if (!g) return []
  return g.sections.flatMap((s) => s.blocks ?? []).flatMap((b) => (b.type === 'table' ? b.rows.map((r) => ({ term: r[0], definition: r[1] })) : []))
}
